"""Generate tests/routes/actions.route: management actions by menu position.

Main menu (SubForm type 3): 0 Matches, 1 Special training, 2 Manage, 3 Edit
team, 4 Info, 5 Settings. GameForm keeps one main-menu SubForm, so its cursor
persists between openings and wraps (form/SubForm.cs select_ modulo the item
count): the generator tracks it. Submenus are new forms (cursor 0). Manage
(type 7) lists, when unlocked by event flags: Trades (12), Fans (14),
Facilities (15), Sponsors (16). Each block opens the item, picks the first
entry, confirms (the default cursor is "Yes") and walks through the messages;
a facility is then placed on the map (GameForm state 1) with SELECT. Weeks
between rounds let results, events and matches happen.
"""
from pathlib import Path

HEADER = """# GENERATED by tests/routes/make_actions_route.py. Do not edit.
# Diagnostic route (no game data): management actions by menu position.
anchor timeout=2400
wait frames=104
key SELECT
wait frames=36
key UP
wait frames=24
key SELECT
wait frames=60
wait not loading stable=20 timeout=900
# A saved game can resume straight into a match day: allow a whole match.
dismiss until form=GameForm label_right=* timeout=6000 optional
"""
SELECTS = """key SELECT
wait frames=50
"""
# Long enough for a whole match (dismiss kicks off and advances it).
BACK = """dismiss until form=GameForm label_right=* timeout=6000 optional
"""
WEEK = """dismiss until form=GameForm label_right=* timeout=200 optional
when form=SubForm label_right=* key SOFT2
wait frames=10
when form=SubForm key RIGHT
wait frames=10
when form=SubForm key SELECT
wait frames=20
key SELECT
wait frames=100
"""
DOWN = "key DOWN\nwait frames=10\n"
MAIN_ITEMS = 6


class Generator:
    def __init__(self):
        self.cursor = 0  # Main-menu cursor after loading a save.

    def open_menu(self, main_index, sub_index=None):
        text = BACK + "key SOFT2\nwait depth=2 timeout=120 optional\nwait frames=20\n"
        text += DOWN * ((main_index - self.cursor) % MAIN_ITEMS) + "key SELECT\nwait frames=40\n"
        self.cursor = main_index
        if sub_index is not None:
            text += DOWN * sub_index + "key SELECT\nwait frames=60\n"
        return text

    def block(self, name, main_index, sub_index=None, selects=5):
        return f"# {name}\n" + self.open_menu(main_index, sub_index) + SELECTS * selects + BACK


def main(rounds=3):
    g = Generator()
    body = ''
    for n in range(rounds):
        body += f"# round {n}\n"
        body += g.block('Manage -> Trades (first player, negotiate)', 2, 0, 6)
        body += g.block('Manage -> Fans (first activity)', 2, 1, 5)
        body += g.block('Manage -> Facilities (first facility, place on the map)', 2, 2, 7)
        body += g.block('Manage -> Sponsors (first sponsor, negotiate)', 2, 3, 6)
        body += g.block('Special training (first entry)', 1, None, 5)
        body += g.block('Edit team (first player, swap)', 3, None, 4)
        body += WEEK * 4
    Path(__file__).with_name('actions.route').write_text(HEADER + body + 'end\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
