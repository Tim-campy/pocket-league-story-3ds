"""Generate tests/routes/career.route: cycles of cup registration and weeks of play.

Each cycle opens the main menu (SOFT2), enters Matches (first item) and its
first entry (cups when the league is still locked), applies to the first cup
and confirms, then passes weeks: match days (bus gather, match, results) need
SELECT pulses, which the week step provides; the year-end question is answered
"No" (RIGHT, SELECT). Leagues unlock through events that follow cup results.
"""
from pathlib import Path

HEADER = """# GENERATED by tests/routes/make_career_route.py. Do not edit.
# Diagnostic route (no game data): cycles of cup registration and weeks of play.
anchor timeout=2400
wait frames=104
key SELECT
wait frames=36
key UP
wait frames=24
key SELECT
wait frames=60
wait not loading stable=20 timeout=900
# A saved game can resume straight into a match day: allow a whole match.
dismiss until form=GameForm label_right=* timeout=6000 optional
"""
REGISTER = """# cycle {n}: apply to the first cup
dismiss until form=GameForm label_right=* timeout=300 optional
key SOFT2
wait depth=2 timeout=120 optional
wait frames=20
key SELECT
wait frames=40
key SELECT
wait frames=60
key SELECT
wait frames=60
key SELECT
wait frames=60
key SELECT
wait frames=40
key SELECT
wait frames=40
dismiss until form=GameForm label_right=* timeout=400 optional
"""
WEEK = """dismiss until form=GameForm label_right=* timeout=200 optional
when form=SubForm label_right=* key SOFT2
wait frames=10
when form=SubForm key RIGHT
wait frames=10
when form=SubForm key SELECT
wait frames=20
key SELECT
wait frames=100
"""


def main(cycles=40, weeks=6):
    text = HEADER + ''.join(REGISTER.format(n=n) + WEEK * weeks for n in range(cycles)) + 'end\n'
    Path(__file__).with_name('career.route').write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
