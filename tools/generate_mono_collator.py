"""Adapt only the pinned MIT Mono collator, not a general C# translator.

The dependency source is hash-checked by setup_mono_collation.py. Public SortKey
production is intentionally absent; the source's internal four-byte comparison
weights remain necessary for cultural search and comparison.
"""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from setup_mono_collation import PINNED, LGPL_PINNED


def active_source(text):
    # Strip comments before preprocessing (disabled blocks contain nested #ifs).
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    active = [True]
    conditions = []
    result = []
    for line in text.splitlines():
        directive = line.strip()
        if directive.startswith('#if '):
            value = directive[4:].strip()
            if value not in ('true', 'false', 'NET_2_0'):
                raise ValueError('Unreviewed preprocessor condition: '+value)
            conditions.append(value != 'false')
            active.append(active[-1] and conditions[-1])
        elif directive == '#else':
            conditions[-1] = not conditions[-1]
            active[-1] = active[-2] and conditions[-1]
        elif directive == '#endif':
            active.pop()
            conditions.pop()
        elif not directive.startswith('#') and active[-1]:
            result.append(line)
    if len(active) != 1:
        raise ValueError('Unbalanced conditional source')
    return '\n'.join(result)


def main():
    relative = 'mcs/class/corlib/Mono.Globalization.Unicode/SimpleCollator.cs'
    path = ROOT/'build/deps/mono-collation'/relative
    if hashlib.sha256(path.read_bytes()).hexdigest() != PINNED[relative]:
        raise ValueError('Official SimpleCollator source identity changed')
    text = path.read_text(encoding='utf-8')
    # Constructor and framework wiring are ported explicitly in managed_collation.cpp.
    part1 = text[text.index('\t\tunsafe byte Category'):text.index('\t\t#region GetSortKey()')]
    part2 = text[text.index('\t\tpublic int Compare (string s1, string s2)'):text.rindex('\t\t#endregion')]
    text = active_source(part1+'\n'+part2)
    text = re.sub(r'\benum ExtenderType\s*\{.*?\}', '', text, flags=re.S)
    text = re.sub(r'\b(ref|out)\s+(int|bool|Context|Contraction)\s+(\w+)', r'\2& \3', text)
    text = re.sub(r'\b(ref|out)\s+', '', text)
    text = re.sub(r'\b(public|private|unsafe)\s+', '', text)
    text = re.sub(r'byte\s*\*\s*(\w+)\s*=\s*stackalloc byte\s*\[(\d+)\]', r'byte \1[\2]{}', text)
    text = re.sub(r'Contraction\s*\[\]', r'Buf<Contraction>', text)
    text = re.sub(r'char\s*\[\]', 'Str', text)
    text = re.sub(r'\bstring\b', 'Str', text)
    text = re.sub(r'\bchar\b', 'char16_t', text)
    text = re.sub(r"'\\u([a-fA-F0-9]{4})'", r'static_cast<char16_t>(0x\1)', text)
    text = re.sub(r'\bnew (Context|PreviousInfo|Escape)\s*\(', r'\1(', text)
    text = re.sub(r'\bnull\b', 'nullptr', text)
    for name in ('COpt', 'CompareOptions', 'ExtenderType', 'Uni'):
        text = text.replace(name+'.', name+'::')
    text = re.sub(r'\b(COpt|CompareOptions)\s+(?!:)', 'int ', text)
    text = text.replace('char16_t::MinValue', 'char16_t{}').replace('char16_t.MinValue', 'char16_t{}')
    text = text.replace('invariant.contractions', 'invariant_contractions')
    text = text.replace('invariant.textInfo', 'TextInfo{CollationCulture{}}')
    for name in ('ct', 'ct1', 'ct2', 'cts'):
        text = re.sub(r'\b'+name+r'\.', name+'->', text)
    text = text.replace('Object.ReferenceEquals (s1, s2)', 's1.same_storage(s2)')
    text = re.sub(r'throw new SystemException \(String.Format \(.*?\)\);', 'throw SystemException("Mono collator internal bounds");', text, flags=re.S)
    # C# shifts mask their count; signed overflowing shifts must not become C++ UB.
    text = text.replace('Level1 (i1) << 8 + Uni::Level3 (i1)', 'shl_i32(Level1(i1), 8 + Uni::Level3(i1))')
    text = text.replace('Level1 (i2) << 8 + Uni::Level3 (i2)', 'shl_i32(Level1(i2), 8 + Uni::Level3(i2))')
    text = re.sub(r'(bool QuickCheckPossible\s*\([^)]*\)\s*\{)', r'\1\n (void)s1; (void)idx1; (void)end1; (void)s2; (void)idx2; (void)end2;', text)
    text = re.sub(r'(int IndexOfSortKey\s*\([^)]*\)\s*\{)', r'\1\n (void)target;', text)
    text = re.sub(r'\n\s*\n\s*\n', '\n\n', text)
    notice = '''// Adapted from Mono SimpleCollator.cs, Atsushi Enomoto.
// Copyright (C) 2005 Novell, Inc. MIT/X11; see THIRD_PARTY.md.
// Generated by tools/generate_mono_collator.py from hash-pinned official source.
// Do not edit this include; change the explicit component adaptation instead.
'''
    output = ROOT/'src/kairo/common/mono_collator_methods.inc'
    output.write_text(notice+text+'\n', encoding='utf-8', newline='\n')
    relative = 'mcs/class/corlib/Mono.Globalization.Unicode/MSCompatUnicodeTable.cs'
    unicode_source = ROOT/'build/deps/mono-collation'/relative
    if hashlib.sha256(unicode_source.read_bytes()).hexdigest() != PINNED[relative]:
        raise ValueError('Official MSCompatUnicodeTable source identity changed')
    unicode_text = unicode_source.read_text(encoding='utf-8')
    unicode_text = unicode_text[unicode_text.index('\t\tpublic static int ToKanaTypeInsensitive'):unicode_text.index('\t\t#endregion', unicode_text.index('\t\tpublic static int ToKanaTypeInsensitive'))]
    unicode_text = active_source(unicode_text)
    unicode_text = re.sub(r'\bpublic\s+', '', unicode_text)
    unicode_text = re.sub(r'\bchar\b', 'char16_t', unicode_text)
    unicode_text = re.sub(r"'\\u([a-fA-F0-9]{4})'", r'static_cast<char16_t>(0x\1)', unicode_text)
    (ROOT/'src/kairo/common/mono_unicode_methods.inc').write_text(notice+unicode_text+'\n', encoding='utf-8', newline='\n')
    # Tables below come ONLY from hash-checked upstream open-source resources.
    folder = ROOT/'build/generated/mono-collation'
    folder.mkdir(parents=True, exist_ok=True)
    lines = ['// Official Mono MIT class-library resources, not extracted Unity bytes.']
    total = 0
    for relative, digest in PINNED.items():
        if '/resources/collation.' not in relative:
            continue
        data = (ROOT/'build/deps/mono-collation'/relative).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('Official resource identity changed')
        name = Path(relative).stem.replace('.', '_')
        lines.append('static constexpr byte '+name+'[] = {')
        lines += [','.join(str(n) for n in data[start:start+32])+',' for start in range(0,len(data),32)]
        lines.append('};')
        total += len(data)
    (folder/'mono_collation_tables.inc').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    print('Official collation table bytes:', total)
    # Separately authorized GNU Library GPLv2 data. Do not merge its attribution
    # into the MIT sources/resources above. NumericData (unused) is not emitted.
    relative='mono/metadata/char-conversions.h'
    source=ROOT/'build/deps/mono-collation'/relative
    if hashlib.sha256(source.read_bytes()).hexdigest()!=LGPL_PINNED[relative]:
        raise ValueError('Historical LGPL BMP source identity changed')
    header=source.read_text(encoding='utf-8')
    arrays={}
    for name in ['CategoryData','ToLowerDataLow','ToLowerDataHigh','ToUpperDataLow','ToUpperDataHigh']:
        match=re.search(r'\b'+name+r'\s*\[\]\s*=\s*\{(.*?)\}',header,re.S)
        if not match:raise ValueError('Historical BMP array absent: '+name)
        arrays[name]=[int(v) for v in re.findall(r'\d+',match.group(1))]
    expected_lengths=[65536,9424,223,9450,223]
    if [len(values) for values in arrays.values()]!=expected_lengths:raise ValueError('Historical BMP shape changed')
    flags=[0]*8192
    categories=arrays.pop('CategoryData')
    for cp,category in enumerate(categories):
        if category==29:flags[cp//8]|=1<<(cp&7)
    ranges=[]
    for cp,category in enumerate(categories):
        if category!=8:continue
        if ranges and ranges[-1][1]+1==cp:ranges[-1][1]=cp
        else:ranges.append([cp,cp])
    digit_lines=['// Derived from official Mono CategoryData, GNU Library GPL version2.',
                 '// Separate license/provenance: THIRD_PARTY.md and third_party/mono-lgpl/COPYING.LIB.',
                 'static constexpr char16_t DecimalDigitRanges[][2] = {']
    digit_lines += ['{'+str(a)+','+str(b)+'},' for a,b in ranges];digit_lines.append('};')
    (folder/'mono_decimal_digit_ranges.inc').write_text('\n'.join(digit_lines)+'\n',encoding='utf-8',newline='\n')
    print('Historical decimal-digit range bytes:',len(ranges)*4)
    data_lines=['// Derived from official Mono char-conversions.h, GNU Library GPL version2.',
                '// Separate license/provenance: THIRD_PARTY.md and third_party/mono-lgpl/COPYING.LIB.']
    data_lines.append('static constexpr std::uint8_t OtherNotAssignedBits[] = {')
    data_lines += [','.join(str(v) for v in flags[i:i+32])+',' for i in range(0,len(flags),32)];data_lines.append('};')
    for name,values in arrays.items():
        data_lines.append('static constexpr char16_t '+name+'[] = {')
        data_lines += [','.join(str(v) for v in values[i:i+24])+',' for i in range(0,len(values),24)];data_lines.append('};')
    (folder/'mono_character_tables.inc').write_text('\n'.join(data_lines)+'\n',encoding='utf-8',newline='\n')
    print('Separately licensed historical BMP data bytes:',len(flags)+sum(len(v)*2 for v in arrays.values()))

if __name__ == '__main__':
    main()
