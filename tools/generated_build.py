"""Incremental object-only build for emitted sources, using installed Ninja/MSVC.

Ninja obtains actual header dependencies from /showIncludes. No source timestamp
is refreshed here unless its generated bytes changed. Build receipts are private.
"""
import hashlib,json,shutil,subprocess,time
from pathlib import Path
from pc_compiler import NINJA,build_jobs,environment,showincludes_prefix

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def escape(value):return str(value).replace('\\','/').replace('$','$$').replace(':','$:').replace(' ','$ ')
def write_changed(path,data):
    path=Path(path);data=data.encode('utf8')if isinstance(data,str)else data
    if not path.exists()or path.read_bytes()!=data:path.write_bytes(data)

def compile_objects(sources,folder,includes,*,optimize=False,jobs=2,log_name='compile'):
    folder=Path(folder).resolve();folder.mkdir(parents=True,exist_ok=True)
    sources=sorted(Path(p).resolve()for p in sources)
    env=environment();compiler=Path(shutil.which('cl.exe',path=env['PATH']))
    policy=folder/'include-prefix/probe.json'
    prefix=json.loads(policy.read_text())if policy.exists()else showincludes_prefix(policy.parent,env)
    if prefix['compiler_sha256']!=sha(compiler):prefix=showincludes_prefix(policy.parent,env)
    options=['/nologo','/c','/showIncludes','/std:c++17','/EHsc','/MD','/fp:strict','/utf-8','/W4','/we4715','/bigobj','/O2'if optimize else '/Od']
    options+=['/I'+str(Path(p).resolve())for p in includes]
    text=['ninja_required_version = 1.10\nrule cxx\n',
          '  command = "'+str(compiler).replace('\\','/')+'" @"$out.rsp"\n',
          '  deps = msvc\n  msvc_deps_prefix = '+prefix['prefix']+'\n',
          '  rspfile = $out.rsp\n  rspfile_content = '+subprocess.list2cmdline(options)+' /Fo$out $in\n']
    objects=[]
    for source in sources:
        obj='unit_'+hashlib.sha256(str(source).encode()).hexdigest()[:16]+'.obj';objects.append(folder/obj)
        text.append('build '+obj+': cxx '+escape(source)+'\n')
    text.append('default '+' '.join(p.name for p in objects)+'\n')
    write_changed(folder/'build.ninja',''.join(text))
    started=time.perf_counter_ns()
    jobs=build_jobs(jobs)
    result=subprocess.run([str(NINJA),'-C',str(folder),'-j',str(jobs)],env=env,capture_output=True)
    elapsed=time.perf_counter_ns()-started
    log=folder/(log_name+'.log');log.write_bytes(result.stdout+result.stderr)
    report=dict(exit_code=result.returncode,elapsed_ns=elapsed,optimization='/O2'if optimize else '/Od',jobs=jobs,
                compiler_sha256=sha(compiler),compiler_options=options,sources=len(sources),objects=[dict(source=str(source),path=str(p),sha256=sha(p))for source,p in zip(sources,objects)if p.exists()],
                ninja_file=dict(path=str(folder/'build.ninja'),sha256=sha(folder/'build.ninja')),
                log_sha256=sha(log),include_prefix=prefix,ninja_sha256=sha(NINJA))
    (folder/(log_name+'.json')).write_text(json.dumps(report,indent=2)+'\n',encoding='utf8',newline='\n')
    if result.returncode:raise RuntimeError('Generated C++ compilation failed; inspect '+str(log))
    return report
